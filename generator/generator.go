package generator

import (
	"strconv"

	"google.golang.org/protobuf/compiler/protogen"
)

const (
	runtimePath protogen.GoImportPath = "github.com/gopherex/natsrpc"
	natsPath    protogen.GoImportPath = "github.com/nats-io/nats.go"
)

func qualified(out *protogen.GeneratedFile, path protogen.GoImportPath, name string) string {
	return out.QualifiedGoIdent(path.Ident(name))
}

func runtimeName(out *protogen.GeneratedFile, name string) string {
	return qualified(out, runtimePath, name)
}

// Generate emits one binding file per generated proto containing services.
func Generate(plugin *protogen.Plugin) error {
	for _, file := range plugin.Files {
		if !file.Generate || len(file.Services) == 0 {
			continue
		}

		output := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+"_natsrpc.pb.go", file.GoImportPath)
		output.P("// Code generated by protoc-gen-go-natsrpc. DO NOT EDIT.")
		output.P("// source: ", file.Desc.Path())
		output.P("package ", file.GoPackageName)

		for _, svc := range file.Services {
			plan, err := planService(file, svc)
			if err != nil {
				return err
			}

			emitService(output, plan)
		}
	}

	return nil
}

func emitService(out *protogen.GeneratedFile, plan servicePlan) {
	name := plan.bindingName()
	out.P("func route", name, "() ", runtimeName(out, "Route"), " {")
	out.P("return ", runtimeName(out, "Route"), "{Prefix: ", strconv.Quote(plan.route.Prefix), ", Service: ",
		strconv.Quote(plan.route.Service), "}")
	out.P("}")
	out.P("type ", name, "Client struct { client *", runtimeName(out, "Client"), " }")
	out.P("func New", name, "Client(conn *", qualified(out, natsPath, "Conn"),
		", codec ", runtimeName(out, "Codec"), ", config ", runtimeName(out, "ClientConfig"),
		") (*", name, "Client,error) {")
	out.P("client, err := ", runtimeName(out, "NewClient"), "(conn, codec, config)")
	out.P("if err != nil { return nil, err }")
	out.P("return &", name, "Client{client: client}, nil")
	out.P("}")

	for _, method := range plan.methods {
		emitClient(out, plan, method)
	}

	if len(plan.methods) > 0 {
		emitRegistration(out, plan)
	}
}

func ctxType(out *protogen.GeneratedFile) string { return qualified(out, "context", "Context") }

func requestType(out *protogen.GeneratedFile, method methodPlan) string {
	return "*" + out.QualifiedGoIdent(method.method.Input.GoIdent)
}

func replyType(out *protogen.GeneratedFile, method methodPlan) string {
	return "*" + out.QualifiedGoIdent(method.method.Output.GoIdent)
}

func emitRegistration(out *protogen.GeneratedFile, plan servicePlan) {
	name := plan.bindingName()
	out.P("type ", name, "Handler interface {")

	for _, method := range plan.methods {
		input := "ctx " + ctxType(out)
		if method.incoming {
			input += ", recv func() (" + requestType(out, method) + ", error)"
		} else {
			input += ", req " + requestType(out, method)
		}

		output := "error"

		switch {
		case method.stream:
			input += ", send func(" + replyType(out, method) + ") error"
		default:
			output = "(" + replyType(out, method) + ", error)"
		}

		out.P(method.method.GoName, "(", input, ") ", output)
	}

	out.P("}")
	out.P("func Register", name, "(ctx ", ctxType(out), ", conn *", qualified(out, natsPath, "Conn"),
		", handler ", name, "Handler, codec ", runtimeName(out, "Codec"), ", config ", runtimeName(out, "ServerConfig"),
		") (*", runtimeName(out, "Registration"), ", error) {")
	out.P("return ", runtimeName(out, "Register"), "(ctx, conn, codec, route", name,
		"(), []", runtimeName(out, "Method"), "{")

	for _, method := range plan.methods {
		const streamField = "Stream"

		mode, adapter, field := "RequestReply", "Unary", "Handle"

		switch {
		case method.incoming && method.stream:
			mode, adapter, field = "BidiReply", "Bidirectional", streamField
		case method.incoming:
			mode, adapter, field = "ClientStreamReply", "ClientStreamed", streamField
		case method.stream:
			mode, adapter, field = "StreamReply", "Streamed", streamField
		}

		req := out.QualifiedGoIdent(method.method.Input.GoIdent)
		out.P("{Name: ", strconv.Quote(method.subject), ", Mode: ", runtimeName(out, mode),
			", ", field, ": ", runtimeName(out, adapter), "(func() *", req, " { return new(", req,
			") }, handler.", method.method.GoName,
			"), Metadata: map[string]string{\"mode\": ", strconv.Quote(mode), "}},")
	}

	out.P("}, config)")
	out.P("}")
}
